// Bundles drizzle-kit's SQL (migrations/<timestamp>_<name>/migration.sql) into
// src/shared/migrations.ts, which the server imports to migrate the content
// database. Devices on older app versions keep reading the replica they pull,
// so content tables change additively only: a destructive statement fails the
// bundle instead of breaking an installed app.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const packageRoot = path.join(import.meta.dirname, "..");
const migrationsDir = path.join(packageRoot, "migrations");
const outputFile = path.join(packageRoot, "src/shared/migrations.ts");

const BREAKPOINT = "--> statement-breakpoint";
const DESTRUCTIVE = [
  /^\s*DROP\s/iu,
  /^\s*ALTER\s+TABLE\s+\S+\s+(?:DROP|RENAME)\s/iu,
  /__new_/iu,
  /^\s*PRAGMA\s+foreign_keys\s*=\s*OFF/iu,
];

const tags = readdirSync(migrationsDir, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .toSorted();

const migrations = tags.map((tag) => {
  const sql = readFileSync(
    path.join(migrationsDir, tag, "migration.sql"),
    "utf-8"
  );
  const statements = sql
    .split(BREAKPOINT)
    .map((statement) => statement.trim())
    .filter((statement) => statement.length > 0);
  for (const statement of statements) {
    if (DESTRUCTIVE.some((pattern) => pattern.test(statement))) {
      throw new Error(
        `${tag} is not additive. Installed apps read content tables as they are; add tables and nullable or defaulted columns only.\n${statement}`
      );
    }
  }
  return { tag, statements };
});

writeFileSync(
  outputFile,
  `// Generated by scripts/bundle-migrations.ts from migrations/. Do not edit;
// run \`bun run db:bundle\` in packages/db-content.
import type { Migration } from "./migrate";

export const migrations: readonly Migration[] = ${JSON.stringify(migrations, null, 2)};
`
);

// Builds src/quran/data/hizb.ts: the first ayah of each of the 240 hizb
// quarters (rub' al-hizb) of the Madinah mushaf.
//
// KFGQPC's text marks a quarter with ۞, but not where a quarter opens a surah
// (199 signs for 240 quarters), so the starts come from Tanzil's metadata and
// the ۞ signs override it: every marked ayah must be a start, and the one
// place Tanzil differs (15:50, marked at 15:49 in KFGQPC) takes KFGQPC's.
//
//   bun run quran:build-hizb [path/to/quran-data.js]
import { createHash } from "node:crypto";
import { existsSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";

import { AYAT } from "../../src/quran";

export const TANZIL_METADATA_URL =
  "https://tanzil.net/res/text/metadata/quran-data.js";
/** Tanzil Quran Metadata ver 1.0 (CC BY 3.0). */
const TANZIL_METADATA_SHA256 =
  "9e9930c592aaa34b5c7a79ff4e99ffdc782263a266090bfe2c49e4ed4bac4ca4";

const QUARTER_COUNT = 240;
const RUB_SIGN = "۞";

const loadMetadata = async (given: string | undefined): Promise<string> => {
  const file = given ?? path.join(tmpdir(), "alrisali-tanzil", "quran-data.js");
  if (!existsSync(file)) {
    const response = await fetch(TANZIL_METADATA_URL);
    if (!response.ok) {
      throw new Error(
        `Download failed: ${response.status} ${TANZIL_METADATA_URL}`
      );
    }
    await Bun.write(file, await response.arrayBuffer());
  }
  const text = await Bun.file(file).text();
  const digest = createHash("sha256").update(text).digest("hex");
  if (digest !== TANZIL_METADATA_SHA256) {
    throw new Error(
      `${file} is not the pinned Tanzil quran-data.js (sha256 ${digest}). Update TANZIL_METADATA_SHA256 only after re-checking the file.`
    );
  }
  return text;
};

/** Tanzil's `QuranData.HizbQaurter` table, without its closing sentinel. */
const tanzilQuarters = (metadata: string): string[] => {
  const start = metadata.indexOf("QuranData.HizbQaurter");
  const table = metadata.slice(start, metadata.indexOf("];", start));
  const keys = [...table.matchAll(/\[(?<surah>\d+), (?<ayah>\d+)\]/gu)].map(
    ({ groups }) => `${groups?.surah}:${groups?.ayah}`
  );
  // The table ends with [115, 1], one past the last ayah.
  return keys.slice(0, QUARTER_COUNT);
};

const main = async () => {
  const quarters = tanzilQuarters(await loadMetadata(process.argv[2]));
  const order = new Map<string, number>(
    AYAT.map(({ key }, index) => [key, index])
  );
  const marked = AYAT.filter(({ text }) => text.startsWith(RUB_SIGN)).map(
    ({ key }) => key
  );
  const markedSet = new Set<string>(marked);

  // Move each unmarked Tanzil start onto the marked ayah next to it.
  const starts = quarters.map((key) => {
    if (markedSet.has(key)) {
      return key;
    }
    const index = order.get(key);
    if (index === undefined) {
      throw new Error(`Tanzil quarter ${key} is not an ayah`);
    }
    const neighbour = [AYAT[index - 1], AYAT[index + 1]].find(
      (ayah) => ayah && markedSet.has(ayah.key) && !quarters.includes(ayah.key)
    );
    if (neighbour) {
      return neighbour.key;
    }
    if (AYAT[index]?.ayah !== 1) {
      throw new Error(`Unmarked quarter ${key} does not open a surah`);
    }
    return key;
  });

  const unplaced = marked.filter((key) => !starts.includes(key));
  if (unplaced.length > 0 || new Set(starts).size !== QUARTER_COUNT) {
    throw new Error(`Quarter starts disagree with ۞: ${unplaced.join(", ")}`);
  }
  const sorted = starts.toSorted(
    (a, b) => (order.get(a) ?? 0) - (order.get(b) ?? 0)
  );
  if (sorted.join(",") !== starts.join(",")) {
    throw new Error("Quarter starts are out of order");
  }

  const out = path.join(import.meta.dir, "../../src/quran/data/hizb.ts");
  await Bun.write(
    out,
    `// Generated by scripts/quran/build-hizb.ts; do not edit.\n// First ayah of each hizb quarter: Tanzil Quran Metadata (CC BY 3.0), corrected to KFGQPC's ۞ signs.\nexport const HIZB_QUARTER_STARTS: readonly \`\${number}:\${number}\`[] = ${JSON.stringify(starts)};\n`
  );
  console.log(`Wrote ${starts.length} quarter starts to ${out}`);
};

await main();

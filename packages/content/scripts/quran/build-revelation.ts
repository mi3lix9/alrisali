// Builds src/quran/data/revelation.ts: for each of the 114 surahs, where it
// was revealed (Meccan or Medinan) and its place in Tanzil's revelation
// order, both from Tanzil's `QuranData.Sura` table.
//
//   bun run quran:build-revelation [path/to/quran-data.js]
import { createHash } from "node:crypto";
import { existsSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";

const TANZIL_METADATA_URL =
  "https://tanzil.net/res/text/metadata/quran-data.js";
/** Tanzil Quran Metadata ver 1.0 (CC BY 3.0); the same pin as build-hizb. */
const TANZIL_METADATA_SHA256 =
  "9e9930c592aaa34b5c7a79ff4e99ffdc782263a266090bfe2c49e4ed4bac4ca4";
const SURAH_COUNT = 114;

const loadMetadata = async (given: string | undefined): Promise<string> => {
  const file = given ?? path.join(tmpdir(), "alrisali-tanzil", "quran-data.js");
  if (!existsSync(file)) {
    const response = await fetch(TANZIL_METADATA_URL);
    if (!response.ok) {
      throw new Error(
        `Download failed: ${response.status} ${TANZIL_METADATA_URL}`
      );
    }
    await Bun.write(file, await response.arrayBuffer());
  }
  const text = await Bun.file(file).text();
  const digest = createHash("sha256").update(text).digest("hex");
  if (digest !== TANZIL_METADATA_SHA256) {
    throw new Error(
      `${file} is not the pinned Tanzil quran-data.js (sha256 ${digest}).`
    );
  }
  return text;
};

const main = async () => {
  const metadata = await loadMetadata(process.argv[2]);
  const start = metadata.indexOf("QuranData.Sura");
  const table = metadata.slice(start, metadata.indexOf("];", start));
  const rows = [
    ...table.matchAll(
      /\[\d+, \d+, (?<order>\d+), \d+, '[^']+', "[^"]+", '[^']+', '(?<type>Meccan|Medinan)'\]/gu
    ),
  ].map(({ groups }) => [
    groups?.type === "Meccan" ? "meccan" : "medinan",
    Number(groups?.order),
  ]);
  const orders = new Set(rows.map(([, order]) => order));
  if (
    rows.length !== SURAH_COUNT ||
    orders.size !== SURAH_COUNT ||
    Math.min(...(orders as Set<number>)) !== 1 ||
    Math.max(...(orders as Set<number>)) !== SURAH_COUNT
  ) {
    throw new Error(
      "Tanzil's surah table is not 114 surahs in revelation order"
    );
  }
  const out = path.join(import.meta.dir, "../../src/quran/data/revelation.ts");
  await Bun.write(
    out,
    `// Generated by scripts/quran/build-revelation.ts; do not edit.\n// Per surah, in mushaf order: [place, revelation order]. Tanzil Quran Metadata (CC BY 3.0).\nexport const REVELATION: readonly (readonly ["meccan" | "medinan", number])[] = ${JSON.stringify(rows)};\n`
  );
  console.log(`Wrote ${rows.length} surahs to ${out}`);
};

await main();
